#!/usr/bin/env node
/*
  Generates a type-only stand-in for @prisma/client from prisma/schema.prisma.

  Why this exists: `prisma generate` downloads its query engine from
  binaries.prisma.sh, so on any machine without access to that host — a
  locked-down CI box, an offline container — there is no @prisma/client at
  all, every `prisma.*` call silently becomes `any`, and `tsc` reports a
  clean build for code that will not compile on Vercel.

  A hand-written stub fixed that, and then went stale the first time the
  schema changed, which is a worse failure than having no stub: it reports
  errors that aren't real and hides ones that are. So it's generated.

  This emits types only — no runtime. It is never imported by the app and
  never shipped; it exists so `npm run typecheck` tells the truth.

      node scripts/gen-prisma-stub.mjs > .prisma-stub.d.ts

  See `npm run typecheck`, which does exactly that and then runs tsc.
*/

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schema = readFileSync(join(root, 'prisma', 'schema.prisma'), 'utf8');

/** Strip comments so they can't be mistaken for fields. */
const clean = schema
  .split('\n')
  .map((line) => line.replace(/\/\/.*$/, ''))
  .join('\n');

const SCALARS = {
  String: 'string',
  Boolean: 'boolean',
  Int: 'number',
  BigInt: 'bigint',
  Float: 'number',
  Decimal: 'Decimal',
  DateTime: 'Date',
  Json: 'any',
  Bytes: 'Buffer',
};

/**
 * Every `model X { … }` / `enum X { … }` block, matched by counting braces.
 *
 * A `[^}]*` body pattern is the obvious way to write this and is wrong: it
 * stops at the first `}`, so a block containing a literal brace — a
 * `@default("{}")` on a Json column, say — is silently truncated to the
 * fields above it. A model quietly missing half its fields is worse than no
 * stub at all, because the typecheck then reports errors that aren't real
 * and hides the ones that are.
 *
 * Braces inside string literals are skipped, which is the only place they
 * can legitimately appear. Comments are already stripped by the caller.
 */
function blocks(kind) {
  const out = [];
  const opener = new RegExp(`^[ \\t]*${kind}\\s+(\\w+)\\s*\\{`, 'gm');

  let m;
  while ((m = opener.exec(clean))) {
    const bodyStart = m.index + m[0].length;
    let depth = 1;
    let i = bodyStart;
    let quote = null;

    while (i < clean.length && depth > 0) {
      const ch = clean[i];
      if (quote) {
        if (ch === '\\') i++;
        else if (ch === quote) quote = null;
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if (ch === '{') {
        depth++;
      } else if (ch === '}') {
        depth--;
      }
      i++;
    }

    if (depth !== 0) {
      throw new Error(
        `Unterminated ${kind} "${m[1]}" in schema.prisma — refusing to emit a partial stub.`
      );
    }

    out.push({ name: m[1], body: clean.slice(bodyStart, i - 1) });
    opener.lastIndex = i;
  }

  return out;
}

const enums = blocks('enum').map(({ name, body }) => ({
  name,
  values: body
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && /^\w+$/.test(l)),
}));

const enumNames = new Set(enums.map((e) => e.name));

const models = blocks('model').map(({ name, body }) => {
  const fields = [];
  for (const raw of body.split('\n')) {
    const line = raw.trim();
    // Skip blank lines and block-level attributes (@@index, @@map, ...).
    if (!line || line.startsWith('@@')) continue;

    const m = /^(\w+)\s+(\w+)(\[\])?(\?)?/.exec(line);
    if (!m) continue;

    const [, fieldName, typeName, list, optional] = m;
    const isModel = !SCALARS[typeName] && !enumNames.has(typeName);

    let ts = SCALARS[typeName] ?? typeName;
    if (list) ts = `${ts}[]`;
    // A list relation is never null; a singular optional one is. Prisma
    // types an unfetched relation as present, which is what the app's
    // `include` calls rely on, so relations are declared as fields here.
    else if (optional) ts = `${ts} | null`;

    fields.push({ name: fieldName, ts, isModel });
  }
  return { name, fields };
});

const camel = (s) => s.charAt(0).toLowerCase() + s.slice(1);

const lines = [];
lines.push('// GENERATED by scripts/gen-prisma-stub.mjs — do not edit by hand.');
lines.push('// Types only, for offline typechecking. Regenerate after any schema change:');
lines.push('//   npm run typecheck');
lines.push("declare module '@prisma/client' {");
lines.push('  export type Decimal = { toString(): string; toNumber(): number };');

for (const e of enums) {
  const union = e.values.map((v) => `'${v}'`).join(' | ');
  const obj = e.values.map((v) => `${v}: "${v}"`).join(', ');
  lines.push(`  export type ${e.name} = ${union};`);
  lines.push(`  export const ${e.name}: { ${obj} };`);
}

for (const model of models) {
  lines.push(`  export type ${model.name} = {`);
  for (const f of model.fields) lines.push(`    ${f.name}: ${f.ts};`);
  lines.push('    _count?: any;');
  lines.push('  };');
}

for (const model of models) {
  const t = model.name;
  lines.push(`  type ${t}Delegate = {`);
  lines.push(`    findMany(args?: any): Promise<${t}[]>;`);
  lines.push(`    findFirst(args?: any): Promise<${t} | null>;`);
  lines.push(`    findUnique(args: any): Promise<${t} | null>;`);
  lines.push(`    findUniqueOrThrow(args: any): Promise<${t}>;`);
  lines.push(`    create(args: any): Promise<${t}>;`);
  lines.push('    createMany(args: any): Promise<{ count: number }>;');
  lines.push(`    update(args: any): Promise<${t}>;`);
  lines.push('    updateMany(args: any): Promise<{ count: number }>;');
  lines.push(`    upsert(args: any): Promise<${t}>;`);
  lines.push(`    delete(args: any): Promise<${t}>;`);
  lines.push('    deleteMany(args?: any): Promise<{ count: number }>;');
  lines.push('    count(args?: any): Promise<number>;');
  lines.push('    aggregate(args: any): Promise<any>;');
  // groupBy is deliberately loose: modelling its result shape properly is
  // beyond a stub, and a wrong shape would be worse than an honest `any`.
  lines.push('    groupBy(args: any): Promise<any[]>;');
  lines.push('  };');
}

lines.push('  export class PrismaClient {');
lines.push('    constructor(args?: any);');
lines.push('    $connect(): Promise<void>;');
lines.push('    $disconnect(): Promise<void>;');
lines.push('    $transaction(args: any, options?: any): Promise<any>;');
lines.push('    $queryRaw(...args: any[]): Promise<any>;');
lines.push('    $executeRaw(...args: any[]): Promise<any>;');
lines.push('    $on(...args: any[]): void;');
lines.push('    $use(...args: any[]): void;');
lines.push('    $extends(...args: any[]): any;');
for (const model of models) lines.push(`    ${camel(model.name)}: ${model.name}Delegate;`);
lines.push('  }');

lines.push('  export namespace Prisma {');
lines.push(
  "    export type TransactionClient = Omit<PrismaClient, '$connect' | '$disconnect' | '$on' | '$transaction' | '$use' | '$extends'>;"
);
lines.push('    export type InputJsonValue = any;');
lines.push('    export type JsonValue = any;');
lines.push('    export type JsonObject = { [k: string]: any };');
lines.push('    export type JsonNull = null;');
lines.push('    export const JsonNull: any;');
lines.push('    export const DbNull: any;');
lines.push('  }');
lines.push('}');

process.stdout.write(lines.join('\n') + '\n');
